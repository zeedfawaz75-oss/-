export function findSector(id: string | null | undefined) {
  if (!id) return null;
  return SECTORS.find((s) => s.id === id) ?? null;
}

/**
 * Sectors kept in the data model (links, DB rows, quick services stay valid)
 * but hidden from the main sectors grid on the home page.
 */
export const HIDDEN_SECTOR_IDS = new Set<string>(["misc"]);

/** Sectors shown in the home page sectors grid. */
export const VISIBLE_SECTORS: Sector[] = SECTORS.filter((s) => !HIDDEN_SECTOR_IDS.has(s.id));

export function findSubsection(sectorId: string, subId: string) {
  return findSector(sectorId)?.subsections.find((s) => s.id === subId) ?? null;
}
